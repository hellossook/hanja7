// picture: 모드 C(그림 → 한자)용 임시 이모지. null이면 모드 C에서 출제하지 않는다.
// words: 그 글자와 "이미 배운 글자"로만 이루어진 낱말. 모드 D(낱말 읽기)에서 출제.

function h(hanja, hun, eum, level, stage, picture, words = [], altHunEum = null) {
  return {
    id: hanja, hanja, hun, eum, hunEum: `${hun} ${eum}`, altHunEum, level,
    chapter: level === 8 ? 0 : parseInt(stage, 10), stage, picture, pictureMode: !!picture,   // '2-3' → 챕터 2
    words: words.map(([word, reading, meaning]) => ({ word, reading, meaning })),
  };
}

